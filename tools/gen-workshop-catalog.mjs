// Generate js/visuals/workshop/catalog.js — the STATIC half of the registry.
//
// The registry (index.js) imports all 206 layer modules, which is 1.6MB the browser
// should not parse unless a workshop layer is actually used. But the NAMES and the
// PARAMETER DEFAULTS are needed at boot, for the visual vocabulary and for
// autocomplete, so they are extracted here at build time and shipped as data.
//
//   node tools/gen-workshop-catalog.mjs
//
// makeParams() returns object literals with no DOM access, so it runs fine in node.
import { readFileSync, writeFileSync } from 'node:fs';

// A handful of layers touch browser globals at MODULE level (a Path2D built once, an
// OffscreenCanvas cached). They never run here — only makeParams() is called — so a
// stub is enough to let the module evaluate. Anything genuinely missing would throw
// with a name, which is the point: a silent {} would ship an empty param table.
const stub = () => new Proxy(function () {}, { get: () => stub(), apply: () => stub(), construct: () => stub() });
for (const g of ['Path2D', 'OffscreenCanvas', 'Image', 'ImageData', 'DOMMatrix', 'devicePixelRatio'])
    if (globalThis[g] === undefined) globalThis[g] = stub();
if (globalThis.document === undefined) globalThis.document = stub();
if (globalThis.window === undefined) globalThis.window = globalThis;
if (globalThis.navigator === undefined) globalThis.navigator = stub();

const reg = readFileSync('js/visuals/workshop/index.js', 'utf8');
const kinds = [...reg.matchAll(/^    ([A-Za-z0-9_]+):\s+\{ label: "((?:[^"\\]|\\.)*)",\s+makeParams: ([A-Za-z0-9_]+),/gm)]
    .map(m => ({ key: m[1], label: m[2], mp: m[3] }));
const files = new Map();
for (const m of reg.matchAll(/^import \{ ([^}]*) \} from '\.\/layers\/([^']+)';$/gm))
    for (const sym of m[1].split(',').map(s => s.trim())) files.set(sym, m[2]);

const flat = (d) => Object.fromEntries(Object.entries(d || {})
    .map(([n, v]) => [n, (v && typeof v === 'object' && 'base' in v) ? v.base : v]));

const params = {};
for (const k of kinds) {
    const mod = await import('../js/visuals/workshop/layers/' + files.get(k.mp));
    params[k.key] = flat(mod[k.mp]());
}
const fx = await import('../js/visuals/workshop/fx/registry.js');
const fxParams = {};
for (const [name, kind] of Object.entries(fx.FX_KINDS)) fxParams[name] = flat(kind.makeParams());

const j = (o) => JSON.stringify(o, null, 0).replace(/","/g, '","');
writeFileSync('js/visuals/workshop/catalog.js',
`// ── Workshop catalog — the static half of the registry ───────────────────────
//
// GENERATED by tools/gen-workshop-catalog.mjs. Do not hand-edit.
//
// index.js imports all ${kinds.length} layer modules — 1.6MB the browser has no business
// parsing in a session that never opens a visual. But the NAMES and the parameter
// DEFAULTS are needed at boot, for the visual vocabulary and for autocomplete, and
// they are just data. So they live here, and the heavy registry loads on demand the
// first time a workshop layer is actually used.
//
// The two cannot drift: this file is generated FROM index.js by running each
// makeParams() at build time, and \`npm\`-free — node tools/gen-workshop-catalog.mjs.

export const WORKSHOP_NAMES = ${j(kinds.map(k => k.key))};
export const WORKSHOP_LABELS = ${j(Object.fromEntries(kinds.map(k => [k.key, k.label])))};
/** kind → { param: default }. What draw() is handed when you set nothing. */
export const WORKSHOP_PARAMS = ${JSON.stringify(params)};
export const WORKSHOP_FX_NAMES = ${j(Object.keys(fxParams))};
export const WORKSHOP_FX_PARAMS = ${JSON.stringify(fxParams)};

export function defaults(kind) { return { ...(WORKSHOP_PARAMS[kind] || {}) }; }
export function fxDefaults(type) { return { ...(WORKSHOP_FX_PARAMS[type] || {}) }; }
/** The first declared param — what a bare bloom(0.4) sets. */
export function fxPrimary(type) { const k = Object.keys(WORKSHOP_FX_PARAMS[type] || {}); return k.length ? k[0] : null; }
`);
console.log('catalog:', kinds.length, 'layers,', Object.keys(fxParams).length, 'fx');
